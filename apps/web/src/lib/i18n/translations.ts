/**
 * Robust Translation Lookup Function
 * Automatically handles:
 * 1. Exact BCP 47 matching (e.g. 'es-419')
 * 2. ISO 639 2-letter language matching (e.g. 'es' -> 'es-419')
 * 3. Graceful fallback to English (en-US)
 * 4. User-provided fallback string or key name
 */
export function translate(key: string, languageTag: string, fallback?: string): string {
  const entry = UI_TRANSLATIONS[key];
  if (!entry) return fallback || key;

  // 1. Exact match
  if (entry[languageTag]) return entry[languageTag];

  // 2. Case-insensitive match
  const lowerTag = languageTag.toLowerCase();
  for (const [k, v] of Object.entries(entry)) {
    if (k.toLowerCase() === lowerTag) return v;
  }

  // 3. Match 2-letter prefix (e.g. 'es-MX' matches 'es-419', 'fr-CA' matches 'fr-FR', 'ht' matches 'ht-HT')
  const prefix = languageTag.split("-")[0].toLowerCase();
  for (const [k, v] of Object.entries(entry)) {
    if (k.toLowerCase().startsWith(prefix)) return v;
  }

  // 4. Fallback to English, then provided fallback
  return entry["en-US"] || fallback || key;
}
