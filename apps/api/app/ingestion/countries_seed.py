def seed_countries(db: Session) -> int:
    """Idempotently inserts or updates authoritative country higher-ed metadata."""
    created_or_updated = 0
    for c_data in COUNTRIES_CATALOG:
        code = c_data["code"].upper()
        existing = db.query(Country).filter(Country.code == code).first()
        if not existing:
            db.add(Country(**c_data))
            created_or_updated += 1
        else:
            changed = False
            for key, val in c_data.items():
                if key != "code" and getattr(existing, key) != val:
                    setattr(existing, key, val)
                    changed = True
            if changed:
                created_or_updated += 1
    db.commit()
    return created_or_updated


def ensure_country_exists(db: Session, country_code: str, fallback_name: str | None = None) -> Country:
    """Ensures a Country row exists for any ISO 3166-1 alpha-2 code before inserting an institution."""
    code = (country_code or "US").strip().upper()[:2]
    existing = db.query(Country).filter(Country.code == code).first()
    if existing:
        return existing

    # Check catalog first
    for c_data in COUNTRIES_CATALOG:
        if c_data["code"] == code:
            c = Country(**c_data)
            db.add(c)
            db.flush()
            return c

    c = Country(
        code=code,
        name=fallback_name or code,
        primary_languages=[],
    )
    db.add(c)
    db.flush()
    return c
