def seed_phase4_financial_and_credentials(db: Session) -> Dict[str, int]:
    """Idempotently seed/enrich scholarships, eligibility rules, grade scales, and recognition rules."""
    for code in ("NG", "BR", "ZA", "MX", "JM", "IB"):
        _ensure_country(db, code)

    # Retire superseded/renamed pre-audit scholarship titles cleanly
    superseded_titles = [
        "UCLA Blue and Gold & Regents Scholarship Framework",
        "Fulbright Foreign Student & Global Exchange Program",
        "TUM Deutschlandstipendium & Bavarian Public Fee Waiver Policy",
        "OAS Academic Scholarship & Leo S. Rowe Pan American Fund (Americas / Caribbean)",
    ]
    db.query(ScholarshipProgram).filter(ScholarshipProgram.title.in_(superseded_titles)).delete(
        synchronize_session=False
    )

    scholarships_created = 0
    scholarships_updated = 0
    rules_created = 0

    for item in PHASE4_SCHOLARSHIPS:
        inst = None
        if item.get("institution_ipeds"):
            inst = db.query(Institution).filter(Institution.ipeds_unit_id == item["institution_ipeds"]).first()
        elif item.get("institution_name"):
            inst = db.query(Institution).filter(Institution.official_name == item["institution_name"]).first()

        # Skip only when an institution-specific scholarship cannot find its target institution
        if (item.get("institution_ipeds") or item.get("institution_name")) and not inst:
            continue

        sch = (
            db.query(ScholarshipProgram)
            .filter(
                ScholarshipProgram.title == item["title"],
                ScholarshipProgram.country_code == item["country_code"],
            )
            .first()
        )
        fields = {
            "institution_id": inst.id if inst else None,
            "country_code": item["country_code"],
            "title": item["title"],
            "applicant_type": item["applicant_type"],
            "funding_type": item["funding_type"],
            "covers_international": item["covers_international"],
            "max_award_info": item["max_award_info"],
            "eligibility_summary": item["eligibility_summary"],
            "provider_type": item.get("provider_type", "university"),
            "award_type": item.get("award_type", "fixed_amount"),
            "award_amount_min_usd": item.get("award_amount_min_usd"),
            "award_amount_max_usd": item.get("award_amount_max_usd"),
            "award_currency": "USD",
            "is_renewable": item.get("is_renewable", True),
            "covers_tuition": item.get("covers_tuition", True),
            "covers_fees": item.get("covers_fees", False),
            "covers_housing": item.get("covers_housing", False),
            "covers_meals": item.get("covers_meals", False),
            "covers_health_insurance": item.get("covers_health_insurance", False),
            "provides_living_stipend": item.get("provides_living_stipend", False),
            "application_deadline_date": item.get("application_deadline_date"),
            "is_deadline_rolling": item.get("is_deadline_rolling", False),
            "min_gpa_4": item.get("min_gpa_4"),
            "requires_financial_need": item.get("requires_financial_need", False),
            "eligible_citizenships": item.get("eligible_citizenships", []),
            "eligible_residency_states": item.get("eligible_residency_states", []),
            "eligible_destination_countries": item.get("eligible_destination_countries", []),
            "degree_levels": item.get("degree_levels", ["bachelors"]),
            "is_guaranteed_statutory": item.get("is_guaranteed_statutory", False),
            "source_name": item["source_name"],
            "source_url": item["source_url"],
            "verified_at": VERIFIED_AT,
            "is_verified": True,
            "is_current": True,
        }

        if not sch:
            sch = ScholarshipProgram(**fields)
            db.add(sch)
            db.flush()
            scholarships_created += 1
        else:
            for k, v in fields.items():
                setattr(sch, k, v)
            scholarships_updated += 1

        existing_labels = {
            r.human_label
            for r in db.query(ScholarshipEligibilityRule)
            .filter(ScholarshipEligibilityRule.scholarship_id == sch.id)
            .all()
        }
        for dim, op, val, label, mandatory in item.get("rules", []):
            if label not in existing_labels:
                db.add(
                    ScholarshipEligibilityRule(
                        scholarship_id=sch.id,
                        rule_dimension=dim,
                        rule_operator=op,
                        rule_value=val,
                        human_label=label,
                        is_mandatory=mandatory,
                    )
                )
                rules_created += 1

    grade_rules_created = 0
    for row in GRADE_CONVERSION_BRACKETS:
        (
            src_cc,
            sys_key,
            scale_name,
            level,
            order,
            min_n,
            max_n,
            raw_lbl,
            class_lbl,
            let_eq,
            g_low,
            g_high,
            g_pt,
            passing,
            inverted,
            meth,
            citation,
            note,
        ) = row
        exists = (
            db.query(GradeConversionRule.id)
            .filter(
                GradeConversionRule.source_country_code == src_cc,
                GradeConversionRule.grading_system_key == sys_key,
                GradeConversionRule.band_order == order,
            )
            .first()
        )
        if not exists:
            db.add(
                GradeConversionRule(
                    source_country_code=src_cc,
                    grading_system_key=sys_key,
                    scale_name=scale_name,
                    academic_level=level,
                    band_order=order,
                    min_numeric=min_n,
                    max_numeric=max_n,
                    raw_grade_label=raw_lbl,
                    classification_label=class_lbl,
                    target_letter_equivalent=let_eq,
                    target_gpa_low=g_low,
                    target_gpa_high=g_high,
                    target_gpa_point=g_pt,
                    is_passing=passing,
                    is_inverted_scale=inverted,
                    methodology=meth,
                    methodology_citation=citation,
                    percentile_note=note,
                    confidence_level="high",
                )
            )
            grade_rules_created += 1

    rec_rules_created = 0
    for rec in CREDENTIAL_RECOGNITION_RECORDS:
        exists = (
            db.query(CredentialRecognitionRule.id)
            .filter(
                CredentialRecognitionRule.source_country_code == rec["source_country_code"],
                CredentialRecognitionRule.destination_country_code == rec["destination_country_code"],
                CredentialRecognitionRule.source_credential_name == rec["source_credential_name"],
            )
            .first()
        )
        if not exists:
            db.add(CredentialRecognitionRule(**rec, verified_at=VERIFIED_AT, verification_status="verified"))
            rec_rules_created += 1

    db.commit()
    return {
        "scholarships_created": scholarships_created,
        "scholarships_updated": scholarships_updated,
        "rules_created": rules_created,
        "grade_rules_created": grade_rules_created,
        "recognition_rules_created": rec_rules_created,
    }
