def _ensure_country(db: Session, code: str) -> None:
    if db.query(Country.code).filter(Country.code == code).first():
        return
    names = {
        "NG": "Nigeria",
        "BR": "Brazil",
        "ZA": "South Africa",
        "MX": "Mexico",
        "JM": "Jamaica",
        "IB": "International Baccalaureate",
    }
    db.add(Country(code=code, name=names.get(code, code), currency_code="USD"))
    db.flush()


